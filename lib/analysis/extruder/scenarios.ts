// Scenario library — the digital twin's 61 verified diagnostic cases.
//
// Generated from the twin's own `VectorSynthesiser` + `ManualVectorBuilder`
// (03_src/ultron_extruder/diagnostics/), so every number here is the number the
// twin itself submits and verifies. Nothing was re-derived by hand.
//
// Each scenario carries the complete eleven-tag measurement vector in canonical
// units, the measurement sequences the temporal cases need, and the outcome the
// twin's own harness expects. `unsupported` is set where the console genuinely
// cannot reproduce the case — 9 mechanical scenarios and the combined case need a
// raw waveform, and the 4 data-quality scenarios need transport metadata. Those
// are listed and explained rather than silently doing nothing.
//
// Status: every value is ENGINEERING_DEVELOPMENT and NOT_FIELD_VALIDATED, exactly
// as in the source.

import type { ExtruderTag } from './signalMap';

export type ScenarioInputMode =
  | 'SNAPSHOT'
  | 'MULTI_SNAPSHOT'
  | 'TEMPORAL_SENSOR_FAULT'
  | 'VIBRATION_SIGNAL'
  | 'DATA_QUALITY_METADATA'
  | 'COMBINED';

/** Acceptance class the twin's harness scores the result against. */
export type ScenarioAcceptance = string;

export type Scenario = {
  id: string;
  /** Condition code from the twin, e.g. SCREEN_RESTRICTION. */
  code: string;
  name: string;
  /** Checklist section letter (A-J) and its title. */
  section: string;
  sectionTitle: string;
  inputMode: ScenarioInputMode;
  severity: number | null;
  /** The component the condition acts on, when the twin declares one. */
  affected: string | null;
  /** What the twin's harness expects this vector to produce. */
  expectedFaultIds: string[];
  acceptance: ScenarioAcceptance;
  notes: string;
  /** Target value per tag, in that tag's canonical unit. */
  measurements: Partial<Record<ExtruderTag, number | null>>;
  /** Scripted measurement sequences, oldest first, for the temporal cases. */
  history: Partial<Record<ExtruderTag, (number | null)[]>>;
  /** Present when the console cannot reproduce this case, with the reason. */
  unsupported?: string;
};

