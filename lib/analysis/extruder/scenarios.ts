const BY_ID = new Map(SCENARIOS.map((scenario) => [scenario.id, scenario]));

export function scenarioById(id: string): Scenario | undefined {
  return BY_ID.get(id);
}

/** Scenarios the console can actually drive. */
export function reproducibleScenarios(): Scenario[] {
  return SCENARIOS.filter((scenario) => !scenario.unsupported);
}

/** Section letter -> title, in checklist order. */
export const SCENARIO_SECTIONS: { letter: string; title: string; count: number }[] = (() => {
  const seen = new Map<string, { letter: string; title: string; count: number }>();
  for (const scenario of SCENARIOS) {
    const existing = seen.get(scenario.section);
    if (existing) existing.count += 1;
    else seen.set(scenario.section, { letter: scenario.section, title: scenario.sectionTitle, count: 1 });
  }
  return [...seen.values()];
})();
